/** 品牌原始串 → 归一到某个 guide（认不出返回 aosp）。 */
export function detectBrand(raw) {
  const s = String(raw == null ? '' : raw).toLowerCase();
  const hit = BRANDS.find((b) => b.keys.some((k) => k && s.includes(k)));
  return hit ? hit.id : 'aosp';
}

/**
 * 「后台运行」这一项的本地叫法：`{page, option}`。
 *
 * ★ 别在 UI 里写死「耗电管理 / 允许完全后台行为」—— 那是 ColorOS 的叫法。
 *   小米叫「省电策略 / 无限制」，华为叫「应用启动管理 / 允许后台活动」，
 *   三星叫「电池 / 不受限制」。所有文案统一走这里。
 */
export function powerTerms(rawBrand) {
  return guideFor(detectBrand(rawBrand)).power;
}

/** 取某个品牌（含兜底）。 */
export function guideFor(id) {
  return BRANDS.find((b) => b.id === id) || BRANDS[BRANDS.length - 1];
}

/**
 * 生成展示顺序：当前品牌第一，其余按固定顺序跟随。
 * @param {string} rawBrand 原生回的 manufacturer/brand 串
 */
export function orderedBrands(rawBrand) {
  const current = detectBrand(rawBrand);
  const first = guideFor(current);
  return { current: first, others: BRANDS.filter((b) => b.id !== first.id) };
}
